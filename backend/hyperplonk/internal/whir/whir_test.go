func randomTable(numVars int) polynomial.MultiLin {
	t := make(polynomial.MultiLin, 1<<numVars)
	for i := range t {
		t[i].MustSetRandom()
	}
	return t
}

func randomPoint(n int) []fr.Element {
	p := make([]fr.Element, n)
	for i := range p {
		p[i].MustSetRandom()
	}
	return p
}

func mustParams(t *testing.T, m int, regime Regime) Params {
	p, err := NewParams(m, 3, 4, 128, regime)
	if err != nil {
		t.Fatal(err)
	}
	return p
}

// W1: the codeword is f(x) = f̂(x, x², x⁴, …) on the subgroup, in natural order.
func TestEncode(t *testing.T) {
	for m := 0; m <= 6; m++ {
		table := randomTable(m)
		logDomain := m + 3
		cw := encode(table.Clone(), logDomain)
		if len(cw) != 1<<logDomain {
			t.Fatal("codeword length")
		}
		for i := range cw {
			x := domainElement(logDomain, i)
			if want := table.Evaluate(pow(x, m), nil); !want.Equal(&cw[i]) {
				t.Fatalf("m=%d: codeword[%d] ≠ f̂(pow(ω^%d))", m, i, i)
			}
		}
	}
}

// L^(2) is generated by the square of L's generator: the domains of
// successive iterations are consistent.
func TestGeneratorsAreConsistent(t *testing.T) {
	for logDomain := 1; logDomain <= 20; logDomain++ {
		g := generator(logDomain)
		var sq fr.Element
		sq.Square(&g)
		if h := generator(logDomain - 1); !h.Equal(&sq) {
			t.Fatalf("generator(%d)² ≠ generator(%d)", logDomain, logDomain-1)
		}
	}
}

// W8 (Claim 4.15): folding a codeword of f̂ with α gives the codeword of
// f̂(α, ·) on the 2^k-th powers of the domain; computed from one leaf.
func TestFoldLeaf(t *testing.T) {
	for _, tc := range []struct{ m, k int }{{4, 1}, {5, 2}, {6, 4}, {4, 4}, {3, 0}} {
		table := randomTable(tc.m)
		logDomain := tc.m + 3
		ls := leaves(encode(table.Clone(), logDomain), tc.k)
		alphas := randomPoint(tc.k)
		folded := table.Clone()
		for _, a := range alphas {
			folded.Fold(a)
		}
		for idx := range ls {
			y := domainElement(logDomain-tc.k, idx)
			want := folded.Evaluate(pow(y, tc.m-tc.k), nil)
			if got := foldLeaf(ls[idx], alphas, logDomain, idx); !got.Equal(&want) {
				t.Fatalf("m=%d k=%d leaf %d: fold ≠ f̂(α, pow(y))", tc.m, tc.k, idx)
			}
		}
	}
}

func TestMerkle(t *testing.T) {
	ls := leaves(randomTable(6), 2)
	tree := newMerkleTree(ls)
	root := tree.root()
	for i := range ls {
		if !verifyPath(root, len(ls), i, ls[i], tree.path(i)) {
			t.Fatalf("leaf %d: honest path rejected", i)
		}
	}
	p := tree.path(3)
	if verifyPath(root, len(ls), 2, ls[3], p) {
		t.Fatal("accepted at another position")
	}
	if verifyPath(root, len(ls), 3, ls[4], p) {
		t.Fatal("accepted another leaf")
	}
	if verifyPath(root, len(ls), 3, ls[3], p[:len(p)-1]) {
		t.Fatal("accepted a short path")
	}
	if verifyPath(root, len(ls), 3, ls[3][:3], p) {
		t.Fatal("accepted a truncated leaf")
	}
	// an inner node must not be accepted as a leaf: the two children hashes
	// of the root, presented as leaf data of a 1-leaf tree
	if len(tree.levels) >= 2 {
		lvl := tree.levels[len(tree.levels)-2]
		var a, b fr.Element
		a.SetBytes(lvl[0][:])
		b.SetBytes(lvl[1][:])
		if verifyPath(root, 1, 0, []fr.Element{a, b}, nil) {
			t.Fatal("inner node accepted as a leaf")
		}
	}
}

func claimsFor(table polynomial.MultiLin, m, n int) []Claim {
	cs := make([]Claim, n)
	for i := range cs {
		cs[i].Point = randomPoint(m)
		cs[i].Value = table.Evaluate(cs[i].Point, nil)
	}
	return cs
}

func TestComplete(t *testing.T) {
	for _, regime := range []Regime{UniqueDecoding, Johnson} {
		for m := 0; m <= 11; m++ {
			p := mustParams(t, m, regime)
			table := randomTable(m)
			c, err := Commit(p, table)
			if err != nil {
				t.Fatal(err)
			}
			for _, nb := range []int{1, 4} {
				claims := claimsFor(table, m, nb)
				proof, err := Open(transcript.New("test"), p, c, claims)
				if err != nil {
					t.Fatal(err)
				}
				if err := Verify(transcript.New("test"), p, c.Root, claims, proof); err != nil {
					t.Fatalf("m=%d %v %d claims: honest proof rejected: %v", m, regime, nb, err)
				}
			}
		}
	}
}

func cloneProof(p *Proof) *Proof {
	q := &Proof{Final: p.Final.Clone()}
	cp := func(r [][]fr.Element) [][]fr.Element {
		out := make([][]fr.Element, len(r))
		for i := range r {
			out[i] = append([]fr.Element(nil), r[i]...)
		}
		return out
	}
	cq := func(qs []Query) []Query {
		out := make([]Query, len(qs))
		for i := range qs {
			for t := range qs[i].Leaves {
				out[i].Leaves = append(out[i].Leaves, append([]fr.Element(nil), qs[i].Leaves[t]...))
				out[i].Paths = append(out[i].Paths, append([]Digest(nil), qs[i].Paths[t]...))
			}
		}
		return out
	}
	q.Initial = cp(p.Initial)
	q.FinalQueries = cq(p.FinalQueries)
	for _, r := range p.Rounds {
		q.Rounds = append(q.Rounds, RoundProof{r.Root, r.OOD, cq(r.Queries), cp(r.Sumcheck)})
	}
	return q
}

// Cheating provers; each sub-test names the check that rejects.
func TestCheaters(t *testing.T) {
	const m = 10 // rounds: k = 4, 4; final polynomial in 2 variables
	p := mustParams(t, m, UniqueDecoding)
	table := randomTable(m)
	c, _ := Commit(p, table)
	claims := claimsFor(table, m, 3)
	var one fr.Element
	one.SetOne()

	open := func(c *Committed, claims []Claim) *Proof {
		proof, err := Open(transcript.New("test"), p, c, claims)
		if err != nil {
			t.Fatal(err)
		}
		return proof
	}
	verify := func(root Digest, claims []Claim, proof *Proof) error {
		return Verify(transcript.New("test"), p, root, claims, proof)
	}
	honest := open(c, claims)
	if err := verify(c.Root, claims, honest); err != nil {
		t.Fatal(err)
	}

	t.Run("false evaluation claim: initial sumcheck", func(t *testing.T) {
		bad := append([]Claim(nil), claims...)
		bad[1].Value.Add(&bad[1].Value, &one)
		err := verify(c.Root, bad, open(c, bad))
		if !errors.Is(err, sumcheck.ErrRoundSum) {
			t.Fatalf("got %v", err)
		}
	})

	// The prover commits to P but runs the protocol with another polynomial
	// Q that satisfies the (false for P) claims. The words differ almost
	// everywhere, so the queries see it.
	t.Run("claims of another polynomial than the committed one", func(t *testing.T) {
		other := randomTable(m)
		fake := &Committed{Root: c.Root, tables: []polynomial.MultiLin{other}, codewords: c.codewords, tree: c.tree}
		bad := claimsFor(other, m, 3)
		err := verify(c.Root, bad, open(fake, bad))
		if !errors.Is(err, sumcheck.ErrRoundSum) {
			t.Fatalf("got %v", err)
		}
	})

	// The committed word is far from every codeword (random word).
	t.Run("committed word is not a codeword", func(t *testing.T) {
		word := make([]fr.Element, len(c.codewords[0]))
		for i := range word {
			word[i].MustSetRandom()
		}
		bad := &Committed{tables: []polynomial.MultiLin{table}, codewords: [][]fr.Element{word}}
		bad.tree = newMerkleTree(leaves(word, p.Rounds[0].Fold))
		bad.Root = bad.tree.root()
		if err := verify(bad.Root, claims, open(bad, claims)); err == nil {
			t.Fatal("accepted")
		}
	})

	t.Run("proof for another commitment", func(t *testing.T) {
		c2, _ := Commit(p, randomTable(m))
		if err := verify(c2.Root, claims, honest); err == nil {
			t.Fatal("accepted")
		}
	})

	t.Run("leaf value changed: Merkle", func(t *testing.T) {
		q := cloneProof(honest)
		l := q.Rounds[0].Queries[0].Leaves[0]
		l[1].Add(&l[1], &one)
		if err := verify(c.Root, claims, q); !errors.Is(err, ErrMerkle) {
			t.Fatalf("got %v", err)
		}
	})

	t.Run("final-round leaf value changed: Merkle", func(t *testing.T) {
		q := cloneProof(honest)
		l := q.FinalQueries[0].Leaves[0]
		l[0].Add(&l[0], &one)
		if err := verify(c.Root, claims, q); !errors.Is(err, ErrMerkle) {
			t.Fatalf("got %v", err)
		}
	})

	t.Run("out-of-domain answer changed", func(t *testing.T) {
		q := cloneProof(honest)
		q.Rounds[0].OOD.Add(&q.Rounds[0].OOD, &one)
		if err := verify(c.Root, claims, q); err == nil {
			t.Fatal("accepted")
		}
	})

	// The next two cheaters deviate in one message and are otherwise
	// consistent with it: the changed message is the one absorbed, so all
	// later challenges and openings fit. tamper changes, in place, the nth
	// message absorbed under a label.
	t.Run("final polynomial changed by the prover: fold check", func(t *testing.T) {
		tr := &tamper{Transcript: transcript.New("test"), label: "whir/final", nth: 1, index: 0}
		proof, err := Open(tr, p, c, claims)
		if err != nil || !tr.done {
			t.Fatal("test setup", err)
		}
		if err := verify(c.Root, claims, proof); !errors.Is(err, ErrFold) {
			t.Fatalf("got %v", err)
		}
	})

	// The last sumcheck message is changed at X = 2 only, so s(0) + s(1)
	// still matches and every round check passes; the oracles and the final
	// polynomial are honest. Only the final constraint check can notice that
	// the running claim is no longer the true sum.
	t.Run("last sumcheck message changed by the prover: constraint check", func(t *testing.T) {
		total := 0
		for _, r := range p.Rounds {
			total += r.Fold
		}
		tr := &tamper{Transcript: transcript.New("test"), label: "sumcheck/round", nth: total, index: 2}
		proof, err := Open(tr, p, c, claims)
		if err != nil || !tr.done {
			t.Fatal("test setup", err)
		}
		if err := verify(c.Root, claims, proof); !errors.Is(err, ErrConstraint) {
			t.Fatalf("got %v", err)
		}
	})

	// Same in the first iteration. The honest continuation then sums to the
	// true value, not to the tampered claim, and the next sumcheck sees it.
	t.Run("first-iteration sumcheck message changed by the prover: next round sum", func(t *testing.T) {
		tr := &tamper{Transcript: transcript.New("test"), label: "sumcheck/round", nth: p.Rounds[0].Fold, index: 2}
		proof, err := Open(tr, p, c, claims)
		if err != nil || !tr.done {
			t.Fatal("test setup", err)
		}
		if err := verify(c.Root, claims, proof); !errors.Is(err, sumcheck.ErrRoundSum) {
			t.Fatalf("got %v", err)
		}
	})

	t.Run("sumcheck message changed after the proof", func(t *testing.T) {
		q := cloneProof(honest)
		q.Rounds[0].Sumcheck[1][2].Add(&q.Rounds[0].Sumcheck[1][2], &one)
		if err := verify(c.Root, claims, q); err == nil {
			t.Fatal("accepted")
		}
	})

	t.Run("wrong shapes", func(t *testing.T) {
		for name, f := range map[string]func(q *Proof){
			"missing iteration":      func(q *Proof) { q.Rounds = q.Rounds[:len(q.Rounds)-1] },
			"missing sumcheck round": func(q *Proof) { q.Initial = q.Initial[:len(q.Initial)-1] },
			"short final polynomial": func(q *Proof) { q.Final = q.Final[:len(q.Final)/2] },
			"missing query":          func(q *Proof) { q.Rounds[0].Queries = q.Rounds[0].Queries[1:] },
			"missing final query":    func(q *Proof) { q.FinalQueries = q.FinalQueries[1:] },
			"short leaf":             func(q *Proof) { q.FinalQueries[0].Leaves[0] = q.FinalQueries[0].Leaves[0][:1] },
			"missing path":           func(q *Proof) { q.FinalQueries[0].Paths = nil },
		} {
			q := cloneProof(honest)
			f(q)
			if err := verify(c.Root, claims, q); err == nil {
				t.Errorf("%s: accepted", name)
			}
		}
	})
}

// tamper is a prover-side transcript that adds 1 to element `index` of the
// nth message absorbed under `label`, in place: the caller's slice (the
// message that ends up in the proof) is changed together with what is hashed.
type tamper struct {
	*transcript.Transcript
	label      string
	nth, index int
	seen       int
	done       bool
}

func (t *tamper) AppendElements(label string, xs ...fr.Element) {
	if label == t.label {
		t.seen++
		if t.seen == t.nth {
			var one fr.Element
			one.SetOne()
			xs[t.index].Add(&xs[t.index], &one)
			t.done = true
		}
	}
	t.Transcript.AppendElements(label, xs...)
}

// proofSize returns the size in bytes of a serialized proof (32 bytes per
// field element and per digest).
func proofSize(p *Proof) int {
	n := 0
	rounds := func(r [][]fr.Element) {
		for _, m := range r {
			n += 32 * len(m)
		}
	}
	queries := func(qs []Query) {
		for _, q := range qs {
			for t := range q.Leaves {
				n += 32 * (len(q.Leaves[t]) + len(q.Paths[t]))
			}
		}
	}
	rounds(p.Initial)
	for _, r := range p.Rounds {
		n += 64
		queries(r.Queries)
		rounds(r.Sumcheck)
	}
	n += 32 * len(p.Final)
	queries(p.FinalQueries)
	return n
}

// expectedSize is the proof size computed from the parameters alone.
func expectedSize(p Params) int {
	n := 0
	for i, r := range p.Rounds {
		n += r.Fold * 3 * 32 // sumcheck rounds, 3 values each
		if i > 0 {
			n += 64 // root, out-of-domain answer
		}
		n += r.Queries * 32 * (1<<r.Fold + r.LogDomain - r.Fold)
	}
	return n + 32<<p.FinalVars
}

func TestProofSize(t *testing.T) {
	for _, regime := range []Regime{UniqueDecoding, Johnson} {
		for _, m := range []int{10, 14} {
			p := mustParams(t, m, regime)
			table := randomTable(m)
			c, _ := Commit(p, table)
			claims := claimsFor(table, m, 1)
			proof, err := Open(transcript.New("test"), p, c, claims)
			if err != nil {
				t.Fatal(err)
			}
			got, want := proofSize(proof), expectedSize(p)
			if got != want {
				t.Fatalf("m=%d %v: size %d, expected from parameters %d", m, regime, got, want)
			}
			t.Logf("m=%d %-14v: %d KiB", m, regime, got/1024)
		}
	}
	for _, regime := range []Regime{UniqueDecoding, Johnson} {
		for _, m := range []int{16, 18, 20, 22} {
			t.Logf("predicted m=%d %-14v: %d KiB", m, regime, expectedSize(mustParams(t, m, regime))/1024)
		}
	}
}

// The batching and combination challenges must depend on the commitments, the
// points and every claimed value. Otherwise a prover could choose a claimed
// value after seeing the challenge that weights it.
func TestStatementIsBound(t *testing.T) {
	const m = 4
	roots := []Digest{{}, {1}}
	points := [][]fr.Element{randomPoint(m), randomPoint(m)}
	values := [][]fr.Element{randomPoint(2), randomPoint(2), randomPoint(2)}
	ch := func(roots []Digest, points, values [][]fr.Element) fr.Element {
		tr := transcript.New("test")
		bindStatement(tr, roots, points, values)
		return tr.Challenge("whir/batch")
	}
	ref := ch(roots, points, values)
	var one fr.Element
	one.SetOne()

	r2 := []Digest{roots[0], {2}}
	if c := ch(r2, points, values); c.Equal(&ref) {
		t.Fatal("challenge does not depend on a commitment")
	}
	for j := range values {
		for k := range values[j] {
			v := [][]fr.Element{append([]fr.Element(nil), values[0]...), append([]fr.Element(nil), values[1]...), append([]fr.Element(nil), values[2]...)}
			v[j][k].Add(&v[j][k], &one)
			if c := ch(roots, points, v); c.Equal(&ref) {
				t.Fatalf("challenge does not depend on value [%d][%d]", j, k)
			}
		}
	}
	p2 := [][]fr.Element{points[0], append([]fr.Element(nil), points[1]...)}
	p2[1][m-1].Add(&p2[1][m-1], &one)
	if c := ch(roots, p2, values); c.Equal(&ref) {
		t.Fatal("challenge does not depend on a point")
	}
}

// Trees of later iterations are built by the prover, who may give leaves any
// size. The verifier must reject a leaf of the wrong size before folding it,
// even when its Merkle path is valid.
func TestLeafSizeIsChecked(t *testing.T) {
	r := Round{NumVars: 4, LogDomain: 7, Fold: 2, Queries: 1}
	// a tree with the right number of leaves, each of size 2 instead of 4
	bad := make([][]fr.Element, r.Leaves())
	for i := range bad {
		bad[i] = randomPoint(2)
	}
	tree := newMerkleTree(bad)
	q := []Query{{Leaves: [][]fr.Element{bad[5]}, Paths: [][]Digest{tree.path(5)}}}
	_, _, err := checkQueries(single(tree.root()), r, []int{5}, q, randomPoint(2))
	if !errors.Is(err, ErrProofShape) {
		t.Fatalf("got %v", err)
	}
	// and each of size 8: the surplus values must not be silently ignored
	for i := range bad {
		bad[i] = randomPoint(8)
	}
	tree = newMerkleTree(bad)
	q = []Query{{Leaves: [][]fr.Element{bad[5]}, Paths: [][]Digest{tree.path(5)}}}
	if _, _, err := checkQueries(single(tree.root()), r, []int{5}, q, randomPoint(2)); !errors.Is(err, ErrProofShape) {
		t.Fatalf("overlong leaf: got %v", err)
	}
}

// Batched opening (Construction 7.4): several polynomials, in several
