// Package hyperplonk implements a transparent proof system for gnark's
// SparseR1CS: the HyperPlonk polynomial IOP with WHIR as the commitment
// scheme. There is no trusted setup, and security rests on a hash function
// only.
//
// Status: research code, not reviewed, NOT zero-knowledge, bn254 only, plain
// gates only (no api.Commit). See backend/hyperplonk/bn254 and
// docs/hyperplonk for what the security claim rests on.
//
// The API mirrors backend/plonk and backend/plonkfri. Adding a curve is
// additive: a new backend/hyperplonk/{curve} package and one more case in
// each function below.
package hyperplonk

import (
	"errors"
	"io"

	"github.com/consensys/gnark-crypto/ecc"
	fr_bn254 "github.com/consensys/gnark-crypto/ecc/bn254/fr"
	"github.com/consensys/gnark/backend"
	"github.com/consensys/gnark/backend/witness"
	"github.com/consensys/gnark/constraint"
	cs_bn254 "github.com/consensys/gnark/constraint/bn254"

	hyperplonk_bn254 "github.com/consensys/gnark/backend/hyperplonk/bn254"
)

// Proof represents a proof generated by Prove.
type Proof interface {
	io.WriterTo
	io.ReaderFrom
}

// ProvingKey represents a proving key.
type ProvingKey interface {
	io.WriterTo
	io.ReaderFrom
	VerifyingKey() interface{}
}

// VerifyingKey represents a verifying key.
type VerifyingKey interface {
	io.WriterTo
	io.ReaderFrom
	NbPublicWitness() int // number of elements expected in the public witness
}

// ErrUnsupported is returned for constraint systems, curves or key and proof
// types this backend does not handle.
var ErrUnsupported = errors.New("hyperplonk: unsupported constraint system, curve or object type")

// Option configures Setup.
type Option func(*config)

type config struct{ regime hyperplonk_bn254.Regime }

// WithJohnsonRegime selects the Johnson-bound parameters of WHIR: proofs are
// less than half the size, and soundness additionally rests on recent
// results that are not yet peer reviewed (docs/hyperplonk/THEORY.md, A1, A2).
// The default is the unique-decoding regime.
func WithJohnsonRegime() Option {
	return func(c *config) { c.regime = hyperplonk_bn254.Johnson }
}

// Setup preprocesses a circuit. It is deterministic and needs no secret.
func Setup(ccs constraint.ConstraintSystem, opts ...Option) (ProvingKey, VerifyingKey, error) {
	var c config
	for _, o := range opts {
		o(&c)
	}
	switch tccs := ccs.(type) {
	case *cs_bn254.SparseR1CS:
		if tccs.Type != constraint.SystemSparseR1CS {
			return nil, nil, ErrUnsupported // R1CS and SparseR1CS share a Go type
		}
		pk, vk, err := hyperplonk_bn254.Setup(tccs, c.regime)
		if err != nil {
			return nil, nil, err
		}
		return pk, vk, nil
	default:
		return nil, nil, ErrUnsupported
	}
}

// Prove generates a proof for a full witness.
func Prove(ccs constraint.ConstraintSystem, pk ProvingKey, fullWitness witness.Witness, opts ...backend.ProverOption) (Proof, error) {
	tccs, ok := ccs.(*cs_bn254.SparseR1CS)
	tpk, ok2 := pk.(*hyperplonk_bn254.ProvingKey)
	if !ok || !ok2 || tccs.Type != constraint.SystemSparseR1CS {
		return nil, ErrUnsupported
	}
	proof, err := hyperplonk_bn254.Prove(tccs, tpk, fullWitness, opts...)
	if err != nil {
		return nil, err
	}
	return proof, nil
}

// Verify checks a proof against a public witness.
func Verify(proof Proof, vk VerifyingKey, publicWitness witness.Witness) error {
	tproof, ok := proof.(*hyperplonk_bn254.Proof)
	tvk, ok2 := vk.(*hyperplonk_bn254.VerifyingKey)
	if !ok || !ok2 {
		return ErrUnsupported
	}
	w, ok := publicWitness.Vector().(fr_bn254.Vector)
	if !ok {
		return witness.ErrInvalidWitness
	}
	return hyperplonk_bn254.Verify(tproof, tvk, w)
}

// NewProvingKey returns an empty proving key to be filled with ReadFrom.
// Only bn254 is supported; other curves panic, like backend/plonk.
func NewProvingKey(curveID ecc.ID) ProvingKey {
	if curveID != ecc.BN254 {
		panic("not implemented")
	}
	return &hyperplonk_bn254.ProvingKey{}
}

// NewVerifyingKey returns an empty verifying key to be filled with ReadFrom.
func NewVerifyingKey(curveID ecc.ID) VerifyingKey {
	if curveID != ecc.BN254 {
		panic("not implemented")
	}
	return &hyperplonk_bn254.VerifyingKey{}
}

// NewProof returns an empty proof to be filled with ReadFrom.
func NewProof(curveID ecc.ID) Proof {
	if curveID != ecc.BN254 {
		panic("not implemented")
	}
	return &hyperplonk_bn254.Proof{}
}
